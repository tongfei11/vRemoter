import Foundation
var keys = [Bool]()
var routes = [Bool]()
let session = HoldVoiceSession(key: { keys.append($0) }, route: { routes.append($0) })
session.start("cast")
session.start("cast")
session.start("x6")
session.stop("cast")
assert(keys == [true], "duplicate start or partial stop must not release key")
session.stop("x6")
session.stop("x6")
assert(keys == [true, false], "last stream must release key exactly once")
session.start("cast")
session.close()
assert(keys == [true, false, true, false], "disconnect/shutdown must release key")
assert(routes == [true, false, true, false])
print("WeChat hold lifecycle passed")
